if (window.SOFORD_I18N_EXTRA) Object.assign(SOFORD_I18N, window.SOFORD_I18N_EXTRA);

const SOFORD_LANGS = [
  { id: "en", label: "English" },
  { id: "zh", label: "中文" },
  { id: "es", label: "Español" },
  { id: "pt", label: "Português" },
  { id: "fr", label: "Français" },
  { id: "de", label: "Deutsch" },
  { id: "ru", label: "Русский" },
  { id: "ar", label: "العربية" },
];
const SOFORD_RTL = new Set(["ar"]);

function sofordLang() {
  let saved = "";
  try { saved = localStorage.getItem("soford.lang") || ""; } catch { /* private mode */ }
  const query = new URLSearchParams(location.search).get("lang") || "";
  const lang = SOFORD_I18N[query] ? query : saved;
  return SOFORD_I18N[lang] ? lang : "en";
}

function sofordT(key, fallback) {
  const lang = document.documentElement.lang || "en";
  const pack = SOFORD_I18N[lang] || SOFORD_I18N.en;
  if (pack[key] != null) return pack[key];
  if (SOFORD_I18N.en[key] != null) return SOFORD_I18N.en[key];
  return fallback ?? key;
}

function sofordApplyI18n() {
  const page = document.body?.dataset.page;
  if (page === "home") {
    document.title = sofordT("meta.homeTitle");
    document.querySelector('meta[name="description"]')?.setAttribute("content", sofordT("meta.homeDesc"));
  }
  if (page === "catalog") {
    document.title = sofordT("meta.catalogTitle");
    document.querySelector('meta[name="description"]')?.setAttribute("content", sofordT("meta.catalogDesc"));
  }
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = sofordT(el.dataset.i18n, el.textContent);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = sofordT(el.dataset.i18nHtml, el.innerHTML);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = sofordT(el.dataset.i18nPlaceholder, el.placeholder);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", sofordT(el.dataset.i18nAria, el.getAttribute("aria-label") || ""));
  });
}

function sofordSetLang(lang) {
  if (!SOFORD_I18N[lang] || lang === document.documentElement.lang) return;
  try { localStorage.setItem("soford.lang", lang); } catch { /* ignore */ }
  const params = new URLSearchParams(location.search);
  params.set("lang", lang);
  location.search = params.toString();
}

function sofordMountLang() {
  const wrap = document.querySelector(".site-header .wrap");
  if (!wrap || wrap.querySelector(".lang-switch")) return;
  const box = document.createElement("div");
  box.className = "lang-switch";
  const current = document.documentElement.lang || "en";
  const select = document.createElement("select");
  select.setAttribute("aria-label", "Language");
  select.innerHTML = SOFORD_LANGS.map((item) =>
    `<option value="${item.id}"${item.id === current ? " selected" : ""}>${item.label}</option>`).join("");
  select.addEventListener("change", () => sofordSetLang(select.value));
  box.append(select);
  const anchor = wrap.querySelector(".header-cta") || wrap.querySelector(".menu-toggle");
  wrap.insertBefore(box, anchor);
}

document.documentElement.lang = sofordLang();
document.documentElement.dir = SOFORD_RTL.has(document.documentElement.lang) ? "rtl" : "ltr";
window.sofordT = sofordT;
window.SOFORD_I18N = SOFORD_I18N;
sofordApplyI18n();
sofordMountLang();
