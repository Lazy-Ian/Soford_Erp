// Exports online ERP products into the static catalog used by the website.
// Usage: node scripts/export-products.mjs [path/to/products.json]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(process.argv[2] ?? resolve(here, "../../SofordRepApi/App_Data/products.json"));
const target = resolve(here, "../data/products.js");

// Order matters: the first matching rule wins.
const CATEGORIES = [
  { id: "artificial-grass", test: /grass|turf|lawn/i },
  { id: "eva-mats", test: /\beva\b|tatami|taekwondo|judo|karate|martial/i },
  { id: "outdoor-playground", test: /playground|dog ?bone|paver|brick|outdoor|granule|track/i },
  { id: "rubber-rolls", test: /\brolls?\b|rolled|stopper/i },
  { id: "gym-tiles", test: /./ },
];

// Spec fields shown on the website, in display order. Keys are matched case-insensitively.
const SPEC_FIELDS = [
  ["Material"], ["Thickness"], ["Size"], ["Width", "Roll Width"], ["Length"], ["Color"],
  ["Pile height"], ["Density"], ["Gauge"], ["Dtex"], ["Backing"], ["Hardness"],
  ["Application", "Usage"], ["Feature", "Function", "Advantage"], ["Fire protection"],
  ["Certificate", "Certification"], ["Warranty"], ["Packing", "Package"], ["Delivery Time"],
];

// Alibaba-style sales words read as low quality to Western buyers; drop them from website titles.
const TITLE_NOISE = [
  /\b(19|20)\d{2}\b/g,
  /\b(hot|best)[ -]?sell(ing|er)?\b/gi,
  /\b(new )?popular\b/gi,
  /\bcheap( price)?\b/gi,
  /\b(china|chinese)( factory| manufacturer| suppliers?)?\b/gi,
  /\bfactory( direct| price| supply| customized)?\b/gi,
  /\bmanufacturer\b/gi,
  /\bwholesale\b/gi,
  /\bat best price\b/gi,
  /\bfrom china\b/gi,
  /\bmade in shandong\b/gi,
  /\b(soford|sfd|sofod)( sfd)?\d*\b/gi,
  /\bused\b/gi,
];
const SMALL_WORDS = new Set(["a", "an", "and", "or", "for", "of", "with", "in", "on", "to", "by", "the", "x"]);

function cleanTitle(title) {
  let t = title;
  for (const re of TITLE_NOISE) t = t.replace(re, " ");
  t = t.replace(/\s*\/\s*/g, "/").replace(/\s+([,.])/g, "$1").replace(/\s{2,}/g, " ").replace(/^[\s,/&-]+|[\s,/&-]+$/g, "");
  // Title Case, keeping units (mm, m²), sizes (1mx1m) and acronyms (EPDM, SGS) as written.
  return t
    .split(" ")
    .map((w, i) => {
      if (/\d/.test(w) || (w === w.toUpperCase() && /[A-Z]{2}/.test(w))) return w;
      const lower = w.toLowerCase();
      if (i > 0 && SMALL_WORDS.has(lower)) return lower;
      return lower.charAt(0).toUpperCase() + lower.slice(1);
    })
    .join(" ");
}

const raw = JSON.parse(readFileSync(source, "utf8").replace(/^﻿/, ""));
const seen = new Set();
const products = [];

for (const p of raw) {
  if (p.remoteStatus !== "online" || !p.images?.length) continue;
  const title = cleanTitle(p.title.replace(/\s+/g, " ").trim());
  const key = title.toLowerCase().replace(/\W+/g, " ").trim();
  if (seen.has(key)) continue;
  seen.add(key);

  const attrs = Object.fromEntries(
    Object.entries(p.attributes ?? {}).map(([k, v]) => [k.toLowerCase(), String(v).trim()]),
  );
  const specs = [];
  for (const [label, ...aliases] of SPEC_FIELDS) {
    const value = [label, ...aliases].map((k) => attrs[k.toLowerCase()]).find(Boolean);
    if (value) specs.push([label, value]);
  }

  const prices = (p.tieredPrices ?? []).map((t) => t.price).filter((n) => n > 0);
  products.push({
    id: p.remoteProductId ?? p.id,
    title,
    category: CATEGORIES.find((c) => c.test.test(title)).id,
    images: p.images.slice(0, 6).map((u) => u.replace(/^\/\//, "https://")),
    priceMin: prices.length ? Math.min(...prices) : p.price,
    priceMax: prices.length ? Math.max(...prices) : p.price,
    unit: p.unit,
    moq: p.minimumOrderQuantity,
    leadTimeDays: p.leadTimeDays,
    keywords: (p.keywords ?? []).flatMap((k) => k.split(/\n|,/)).map((k) => k.trim()).filter(Boolean).slice(0, 6),
    specs,
  });
}

const counts = products.reduce((acc, p) => ((acc[p.category] = (acc[p.category] ?? 0) + 1), acc), {});
const banner = `// Generated by scripts/export-products.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n`;
writeFileSync(target, `${banner}window.SOFORD_PRODUCTS = ${JSON.stringify(products)};\n`);
console.log(`Exported ${products.length} products to ${target}`, counts);
